-- Sutra — PostgreSQL schema
-- Apply with:  node sql/apply-schema.mjs   (safe to re-run)
--
-- Times are timestamptz (stored in UTC). Emails are always stored lower case
-- by the app (normalizeEmail), so a plain UNIQUE is enough to keep them unique.

CREATE TABLE IF NOT EXISTS users (
  id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          varchar(120) NOT NULL,
  email         varchar(190) NOT NULL,
  password_hash varchar(100) NOT NULL,
  phone         varchar(20)  DEFAULT NULL,
  role          text         NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
  created_at    timestamptz  NOT NULL DEFAULT now(),
  updated_at    timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT uq_users_phone UNIQUE (phone)
);

-- PostgreSQL has no ON UPDATE CURRENT_TIMESTAMP; a trigger keeps updated_at.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS users_updated_at ON users;
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Orders keep the human-readable id the checkout already generates (SUT-…).
-- `email` is not a foreign key: guest checkout is allowed and leaves no account.
CREATE TABLE IF NOT EXISTS orders (
  id             varchar(32)   PRIMARY KEY,
  email          varchar(190)  NOT NULL DEFAULT '',
  placed_at      timestamptz   NOT NULL,
  updated_at     timestamptz   DEFAULT NULL,
  total          numeric(10,2) NOT NULL,
  discount       numeric(10,2) DEFAULT NULL,
  coupon_code    varchar(40)   DEFAULT NULL,
  payment_method text          NOT NULL DEFAULT 'cod' CHECK (payment_method IN ('cod', 'card')),
  address        varchar(500)  NOT NULL,
  customer_name  varchar(120)  DEFAULT NULL,
  phone          varchar(20)   DEFAULT NULL,
  status         text          NOT NULL DEFAULT 'Processing'
                 CHECK (status IN ('Processing', 'Shipped', 'Delivered', 'Cancelled', 'Return Requested', 'Returned'))
);
CREATE INDEX IF NOT EXISTS idx_orders_email ON orders (email);
CREATE INDEX IF NOT EXISTS idx_orders_placed_at ON orders (placed_at);

-- One row per line item. Deleting an order takes its lines with it.
CREATE TABLE IF NOT EXISTS order_items (
  id         integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   varchar(32)   NOT NULL REFERENCES orders (id) ON DELETE CASCADE ON UPDATE CASCADE,
  product_id varchar(64)   NOT NULL DEFAULT '',
  slug       varchar(160)  NOT NULL DEFAULT '',
  name       varchar(200)  NOT NULL,
  size       varchar(32)   NOT NULL,
  quantity   integer       NOT NULL DEFAULT 1 CHECK (quantity >= 0),
  price      numeric(10,2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items (order_id);

-- Reviews. `order_id` is set only for the post-delivery feedback flow; reviews
-- written straight from a product page leave it NULL.
CREATE TABLE IF NOT EXISTS reviews (
  id         varchar(64)  PRIMARY KEY,
  product_id varchar(64)  NOT NULL,
  order_id   varchar(32)  DEFAULT NULL REFERENCES orders (id) ON DELETE CASCADE ON UPDATE CASCADE,
  author     varchar(120) NOT NULL,
  rating     smallint     NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body       varchar(500) NOT NULL DEFAULT '',
  written_at timestamptz  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reviews_product ON reviews (product_id);
CREATE INDEX IF NOT EXISTS idx_reviews_order ON reviews (order_id);

-- ---------------------------------------------------------------------------
-- Password-reset codes.
--
-- The code itself is never stored, only an HMAC of it. The row exists so that
-- failed attempts can be COUNTED: the old design put a signed challenge in the
-- browser and kept no server record, so nothing could tell that the same code
-- had already been guessed wrongly a thousand times.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS otp_challenges (
  id         varchar(64)  PRIMARY KEY,
  identifier varchar(190) NOT NULL,
  code_hash  varchar(120) NOT NULL,
  expires_at timestamptz  NOT NULL,
  attempts   smallint     NOT NULL DEFAULT 0,
  used       boolean      NOT NULL DEFAULT false,
  dead       boolean      NOT NULL DEFAULT false,
  created_at timestamptz  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_otp_challenges_identifier ON otp_challenges (identifier, created_at);

-- Escalating cooldown, one row per address (and per "login:" email for the
-- wrong-password limit).
--
-- This pauses password RESET only. The account is never locked: if a wrong
-- guess could lock the account, anyone could disable any customer just by
-- requesting a reset for their address and failing the code on purpose.
CREATE TABLE IF NOT EXISTS otp_locks (
  identifier   varchar(190) PRIMARY KEY,
  dead_streak  smallint     NOT NULL DEFAULT 0,
  strikes      smallint     NOT NULL DEFAULT 0,
  paused_until timestamptz  DEFAULT NULL,
  updated_at   timestamptz  NOT NULL
);
